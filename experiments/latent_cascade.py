"""Prototype: GRN as the transition operator of a latent dynamical system (toy A->B->C cascade).

Question 1 (indirect edges): if the regulatory matrix W is learned by propagating latent state
forward in time, does it omit the spurious direct A->C edge that A->B->C induces?
Question 2 (Markov assumption): given the current state, do *earlier* velocities carry extra
information about later states?

Simulation (known kinetics, Euler-Maruyama, dt = 0.005; observed every 0.2 time units, 41 points):
    dA = -gA*A dt                                   (A starts high, decays: a clean pulse)
    dB = (b0 + VB*hill(A) - gB*B) dt + s dW
    dC = (b0 + VC*hill(B) - gC*C) dt + s dW,   hill(x) = x^2/(K^2+x^2)
    observed x = state + N(0, (noise * per-gene sd)^2)
Conditions:
    full_lownoise   observe A,B,C; measurement noise 5%;  latent dim 3
    full_highnoise  observe A,B,C; measurement noise 20%; latent dim 3
    hiddenB_noslot  observe A,C only (B unmeasured);      latent dim 2
    hiddenB_slot    observe A,C only;                     latent dim 3 (one free latent unit,
                    initialised per window from (x_t, x_t - x_{t-1}))
    hiddenB_randB0  observe A,C; B0 ~ U(0, 2) independent of A (Markov-test positive control)
    hiddenB_slot_fromstart  as above, but the free unit starts from a learned constant (no data
                    input) and the model is rolled out over the whole trajectory from t = 0, so the
                    unit can only carry information that the dynamics (edges into it) put there

Model (latent neural ODE with an interpretable linear coupling):
    encoder   z_i = x_i + MLP_i(x_i) per observed gene (gene-aligned latent);
              free latent units are initialised from (x_t, x_t - x_{t-1}) by a small MLP
    dynamics  dz/dt = W @ sigmoid(a*(z - c)) - softplus(g)*z + b    (diag(W) = 0; W = the GRN)
    decoder   x_i = z_i + MLP_i(z_i) for observed genes
    loss      K-step rollout MSE (Euler, 4 substeps per interval) + reconstruction + lam*|W|_1
Ablations isolate what removes the A->C edge: rollout horizon K (10 vs 1) x L1 strength, swept over
a lambda grid (the L1 scale interacts with K, so a single lambda would not be a fair comparison).
Baselines: pooled correlation, best lagged correlation, pairwise Granger, multivariate Lasso-VAR.

Usage:  python experiments/latent_cascade.py run <condition> <seed>
        python experiments/latent_cascade.py report
"""
