OUT = ROOT / "results/latent_cascade"
CONDS = {
    "full_lownoise": dict(obs=[0, 1, 2], noise=0.05, latent=3),
    "full_highnoise": dict(obs=[0, 1, 2], noise=0.20, latent=3),
    "hiddenB_noslot": dict(obs=[0, 2], noise=0.05, latent=2),
    "hiddenB_slot": dict(obs=[0, 2], noise=0.05, latent=3),
    # free unit must be generated by the dynamics: starts from a learned constant (no data input)
    # and is rolled out over the whole trajectory, so its only information source is regulation
    "hiddenB_slot_fromstart": dict(obs=[0, 2], noise=0.05, latent=3, init="start", Ks=(40,),
                                   lams=[0.0, 1e-4, 1e-3, 3e-3, 1e-2], iters=1200),
    # Markov positive control: B starts at an independent random level, so the unobserved B is
    # NOT recoverable from the current (A, C); earlier velocities of C should then carry information
    "hiddenB_randB0": dict(obs=[0, 2], noise=0.05, latent=2, B0max=2.0),
    # Q3: perturbation data. B is unmeasured; a fraction of cells carries a B knockdown (B production
    # x0.1, CRISPRi-like). 'modeled' = the model knows which cells are knocked down and applies the
    # knockdown to its free latent unit with a learned efficiency; 'unmodeled' = labels ignored.
    "hiddenB_KD50_unmodeled": dict(obs=[0, 2], noise=0.05, latent=3, init="start", Ks=(40,),
                                   lams=[0.0, 1e-4, 1e-3, 3e-3, 1e-2], iters=1200, kd_frac=0.5, model_kd=False),
    "hiddenB_KD50_modeled": dict(obs=[0, 2], noise=0.05, latent=3, init="start", Ks=(40,),
                                 lams=[0.0, 1e-4, 1e-3, 3e-3, 1e-2], iters=1200, kd_frac=0.5, model_kd=True),
    "hiddenB_KD25_modeled": dict(obs=[0, 2], noise=0.05, latent=3, init="start", Ks=(40,),
                                 lams=[0.0, 1e-4, 1e-3, 3e-3, 1e-2], iters=1200, kd_frac=0.25, model_kd=True),
}
KD_STRENGTH = 0.1  # true knockdown: B production multiplied by this
SEEDS = [0, 1, 2]
KIN = dict(gA=1.0, gB=0.8, gC=0.6, VB=2.0, VC=2.0, K=0.6, b0=0.05, s=0.03)
N_CELLS, N_TRAIN, T_OBS, DT_OBS, DT_SIM = 200, 150, 41, 0.2, 0.005
H, D = 5, 3          # Markov test: forecast horizon (steps) and lag of the "early" velocity
EDGE_FRAC = 0.10     # edge called if strength >= 10% of the strongest edge
LAMS = [0.0, 1e-5, 3e-5, 1e-4, 3e-4, 1e-3, 3e-3, 1e-2]
MARKOV_MODEL = (10, 1e-3)  # (K, lambda) of the model used for the model-based Markov test (fixed in advance)
GENES = ["A", "B", "C"]


# ----------------------------------------------------------------- simulation
def simulate(rng, B0max=0.3, kd=None):
    k = KIN
    hill = lambda x: x ** 2 / (k["K"] ** 2 + x ** 2)
    x = np.c_[rng.uniform(0.5, 3.0, N_CELLS), rng.uniform(0, B0max, N_CELLS), rng.uniform(0, 0.3, N_CELLS)]
    every = int(round(DT_OBS / DT_SIM))
    traj = np.zeros((N_CELLS, T_OBS, 3))
    traj[:, 0] = x
    for t in range(1, (T_OBS - 1) * every + 1):
        kdB = 1.0 if kd is None else np.where(kd, KD_STRENGTH, 1.0)
        dx = np.c_[-k["gA"] * x[:, 0],
                   kdB * (k["b0"] + k["VB"] * hill(x[:, 0])) - k["gB"] * x[:, 1],
                   k["b0"] + k["VC"] * hill(x[:, 1]) - k["gC"] * x[:, 2]]
        x = x + dx * DT_SIM
        x[:, 1:] += k["s"] * np.sqrt(DT_SIM) * rng.standard_normal((N_CELLS, 2))
        x = np.maximum(x, 0)
        if t % every == 0:
            traj[:, t // every] = x
    return traj


# ----------------------------------------------------------------- model
class GeneMLP(nn.Module):
    """Independent residual 1-D MLP per gene: y_i = x_i + f_i(x_i)."""
    def __init__(self, n, h=16):
        super().__init__()
        self.w1 = nn.Parameter(torch.randn(n, h) * 0.5); self.b1 = nn.Parameter(torch.zeros(n, h))
        self.w2 = nn.Parameter(torch.zeros(n, h))
    def forward(self, x):
        return x + (torch.tanh(x[..., None] * self.w1 + self.b1) * self.w2).sum(-1)


class LatentGRN(nn.Module):
    def __init__(self, n_obs, n_lat, const_init=False, kd_target=None):
        super().__init__()
        self.const_init = const_init
        self.kd_target = kd_target
        self.kd_logit = nn.Parameter(torch.tensor(0.0))  # learned knockdown efficiency (sigmoid)
        self.n_obs, self.n_lat = n_obs, n_lat
        self.enc, self.dec = GeneMLP(n_obs), GeneMLP(n_obs)
        self.free = n_lat - n_obs
        if self.free:
            self.init_free = nn.Sequential(nn.Linear(2 * n_obs, 16), nn.Tanh(), nn.Linear(16, self.free))
            self.z0_free = nn.Parameter(torch.zeros(self.free))
        self.W = nn.Parameter(0.01 * torch.randn(n_lat, n_lat))
        self.register_buffer("mask", 1 - torch.eye(n_lat))
        self.a = nn.Parameter(torch.zeros(n_lat)); self.c = nn.Parameter(torch.zeros(n_lat))
        self.g = nn.Parameter(torch.zeros(n_lat)); self.b = nn.Parameter(torch.zeros(n_lat))

    def Wm(self):
        return self.W * self.mask

    def act(self, z):
        return torch.sigmoid((F.softplus(self.a) + 0.1) * (z - self.c))

    def kd_eff(self):
        return torch.sigmoid(self.kd_logit)

    def f(self, z, kd=None):
        prod = self.act(z) @ self.Wm().T + self.b
        if kd is not None and self.kd_target is not None:
            scale = torch.ones_like(prod)
            scale[:, self.kd_target] = torch.where(kd, self.kd_eff(), torch.ones_like(self.kd_logit))
            prod = prod * scale
        return prod - F.softplus(self.g) * z

    def encode(self, x_t, x_prev):
        z = self.enc(x_t)
        if self.free:
            zf = (self.z0_free.expand(x_t.shape[0], -1) if self.const_init
                  else self.init_free(torch.cat([x_t, x_t - x_prev], -1)))
            z = torch.cat([z, zf], -1)
        return z

    def rollout(self, z, K, sub=4, kd=None):
        out, h = [], DT_OBS / sub
        for _ in range(K):
            for _ in range(sub):
                z = z + h * self.f(z, kd)
            out.append(z)
        return torch.stack(out, 1)  # (B, K, n_lat)

    def forecast(self, x_t, x_prev, K, kd=None):
        return self.dec(self.rollout(self.encode(x_t, x_prev), K, kd=kd)[..., :self.n_obs])

    def latent_traj(self, x_t, x_prev, K, kd=None):
        return self.rollout(self.encode(x_t, x_prev), K, kd=kd)


def train(X, n_lat, K, lam, seed, iters=2000, from_start=False, kd=None, kd_target=None):
    torch.manual_seed(seed)
    Xt = torch.tensor(X, dtype=torch.float32)
    n, T, n_obs = Xt.shape
    m = LatentGRN(n_obs, n_lat, const_init=from_start, kd_target=kd_target)
    KDt = torch.tensor(kd) if kd is not None else None
    opt = torch.optim.Adam(m.parameters(), lr=1e-2)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, iters)
    starts = torch.arange(1, T - K) if not from_start else torch.zeros(1, dtype=torch.long)
    for it in range(iters):
        ci = torch.randint(0, n, (256,)); ti = starts[torch.randint(0, len(starts), (256,))]
        if from_start:
            ti = torch.zeros_like(ti)
        x_t, x_prev = Xt[ci, ti], Xt[ci, torch.clamp(ti - 1, min=0)]
        tgt = torch.stack([Xt[ci, ti + k] for k in range(1, K + 1)], 1)
        pred = m.forecast(x_t, x_prev, K, kd=None if KDt is None else KDt[ci])
        rec = m.dec(m.enc(x_t))
        loss = F.mse_loss(pred, tgt) + F.mse_loss(rec, x_t) + lam * m.Wm().abs().sum()
        opt.zero_grad(); loss.backward(); opt.step(); sched.step()
    return m, float(loss.detach())


def edge_strength(m, X, from_start=False, kd=None):
    """|W_ij| x (range of regulator j's activation over the data): latent-units/time.

    For window-initialised models the latent states come from the encoder; for models rolled out
    from t = 0 (free units start from a constant) they must come from the rollout itself, otherwise
    free units look constant and every edge leaving them scores 0.
    """
    with torch.no_grad():
        Xt = torch.tensor(X, dtype=torch.float32)
        if from_start:
            z = m.latent_traj(Xt[:, 0], Xt[:, 0], X.shape[1] - 1,
                              kd=None if kd is None else torch.tensor(kd)).reshape(-1, m.n_lat)
        else:
            z = m.encode(Xt[:, 1:].reshape(-1, X.shape[2]), Xt[:, :-1].reshape(-1, X.shape[2]))
        a = m.act(z)
        rng = (a.max(0).values - a.min(0).values).numpy()
        return np.abs(m.Wm().numpy()) * rng[None, :]


# ----------------------------------------------------------------- baselines
def baselines(X, obs):
    """Score the candidate direct edge A->C (and true edges where observable)."""
    from sklearn.linear_model import LassoCV, LinearRegression
    iA, iC = obs.index(0), obs.index(2)
    flat = X.reshape(-1, X.shape[2])
    r = {"pooled_corr_A_C": float(np.corrcoef(flat[:, iA], flat[:, iC])[0, 1])}
    lags = []
    for L in range(1, 16):
        a, c = X[:, :-L, iA].ravel(), X[:, L:, iC].ravel()
        lags.append(np.corrcoef(a, c)[0, 1])
    r["max_lagged_corr_A_to_C"] = float(np.max(lags)); r["best_lag_steps"] = int(np.argmax(lags) + 1)
    # pairwise Granger: does A_t improve prediction of C_{t+1} beyond C_t?  (in-sample R2 gain)
    y = X[:, 1:, iC].ravel(); c0 = X[:, :-1, iC].ravel()[:, None]; a0 = X[:, :-1, iA].ravel()[:, None]
    r0 = LinearRegression().fit(c0, y).score(c0, y); r1 = LinearRegression().fit(np.c_[c0, a0], y).score(np.c_[c0, a0], y)
    r["pairwise_granger_R2_gain_A_to_C"] = float(r1 - r0)
    # multivariate Lasso-VAR on finite-difference velocity of C (standardised regressors)
    V = (X[:, 1:, iC] - X[:, :-1, iC]).ravel() / DT_OBS
    Z = X[:, :-1, :].reshape(-1, X.shape[2]); Z = (Z - Z.mean(0)) / Z.std(0)
    las = LassoCV(cv=5, random_state=0).fit(Z, V)
    r["lassoVAR_coef_on_vC"] = {GENES[g]: float(las.coef_[k]) for k, g in enumerate(obs)}
    return r


# ----------------------------------------------------------------- Markov test
def markov_rows(X, cells):
    rows = []
    for c in cells:
        for t in range(D + 1, X.shape[1] - H):
            rows.append((c, t))
    return np.array(rows)


def markov_test(X, m, test_cells, truth=None):
    from sklearn.ensemble import HistGradientBoostingRegressor as HGB
    from sklearn.model_selection import GroupKFold

    def cv_r2(F_, Y, groups):
        r2 = []
        for j in range(Y.shape[1]):
            pred = np.zeros(len(Y))
            for tr, te in GroupKFold(5).split(F_, Y[:, j], groups):
                pred[te] = HGB(max_iter=200, random_state=0).fit(F_[tr], Y[tr, j]).predict(F_[te])
            r2.append(1 - ((Y[:, j] - pred) ** 2).sum() / ((Y[:, j] - Y[:, j].mean()) ** 2).sum())
        return float(np.mean(r2))

    R = {}
    allc = np.arange(X.shape[0])
    rows = markov_rows(X, allc); c, t = rows[:, 0], rows[:, 1]
    x_now, y_fut = X[c, t], X[c, t + H]
    v_early = (X[c, t - D] - X[c, t - D - 1]) / DT_OBS
    v_now = (X[c, t] - X[c, t - 1]) / DT_OBS
    base = cv_r2(x_now, y_fut, c)
    R["modelfree_R2_state_only"] = base
    R["modelfree_dR2_add_early_velocity"] = cv_r2(np.c_[x_now, v_early], y_fut, c) - base
    R["modelfree_dR2_add_current_velocity"] = cv_r2(np.c_[x_now, v_now], y_fut, c) - base
    if truth is not None:  # noise-free, fully observed reference: should be ~0 for a Markov system
        tn, tf = truth[c, t], truth[c, t + H]
        te = (truth[c, t - D] - truth[c, t - D - 1]) / DT_OBS
        b0 = cv_r2(tn, tf, c)
        R["reference_true_state_dR2_add_early_velocity"] = cv_r2(np.c_[tn, te], tf, c) - b0
    if m is None:
        return R
    # model-based: can early velocity explain the trained model's H-step forecast residuals?
    rows = markov_rows(X, test_cells); c, t = rows[:, 0], rows[:, 1]
    with torch.no_grad():
        fc = m.forecast(torch.tensor(X[c, t], dtype=torch.float32),
                        torch.tensor(X[c, t - 1], dtype=torch.float32), H)[:, -1].numpy()
    resid = X[c, t + H] - fc
    v_early = (X[c, t - D] - X[c, t - D - 1]) / DT_OBS
    R["model_forecast_R2_H_steps"] = float(np.mean([1 - ((X[c, t + H, j] - fc[:, j]) ** 2).sum() /
                                                    ((X[c, t + H, j] - X[c, t + H, j].mean()) ** 2).sum()
                                                    for j in range(X.shape[2])]))
    R["model_residual_R2_from_early_velocity"] = cv_r2(np.c_[v_early, X[c, t]], resid, c) - cv_r2(X[c, t], resid, c)
    return R


# ----------------------------------------------------------------- one run
def run(cond, seed):
    cfg = CONDS[cond]; obs = cfg["obs"]
    rng = np.random.default_rng(seed)
    kd = rng.random(N_CELLS) < cfg["kd_frac"] if cfg.get("kd_frac") else None
    truth = simulate(rng, cfg.get("B0max", 0.3), kd=kd)
    X = truth[:, :, obs] + cfg["noise"] * truth[:, :, obs].std((0, 1)) * rng.standard_normal(truth[:, :, obs].shape)
    perm = rng.permutation(N_CELLS); tr, te = perm[:N_TRAIN], perm[N_TRAIN:]
    lat_names = [GENES[g] for g in obs] + [f"h{k}" for k in range(cfg["latent"] - len(obs))]
    res = {"condition": cond, "seed": seed, "latent_names": lat_names, "kinetics": KIN, "variants": {}}
    main_model = None
    start = cfg.get("init") == "start"
    for K in cfg.get("Ks", (10, 1)):
        for lam in cfg.get("lams", LAMS):
            name = f"K{K}_lam{lam:g}"
            t0 = time.time()
            model_kd = cfg.get("model_kd", False)
            m, final_loss = train(X[tr], cfg["latent"], K, lam, seed, iters=cfg.get("iters", 2000), from_start=start,
                                  kd=kd[tr] if model_kd else None, kd_target=len(obs) if model_kd else None)
            S = edge_strength(m, X[tr], from_start=start, kd=kd[tr] if model_kd else None)
            called = S >= EDGE_FRAC * S.max() if S.max() > 1e-6 else np.zeros_like(S, bool)
            iA, iC = lat_names.index("A"), lat_names.index("C")
            v = {"K": K, "lam": lam, "final_loss": final_loss, "seconds": time.time() - t0,
                 "strength": S.round(4).tolist(), "W": m.Wm().detach().numpy().round(4).tolist(),
                 "called_edges": [f"{lat_names[j]}->{lat_names[i]}" for i, j in zip(*np.nonzero(called))],
                 "A_to_C_strength_rel_max": float(S[iC, iA] / S.max()) if called.any() else float("nan"),
                 "direct_A_to_C_called": bool(called[iC, iA]), "empty_graph": bool(not called.any())}
            if "B" in lat_names:
                iB = lat_names.index("B")
                v["true_edges_recovered"] = bool(called[iB, iA] and called[iC, iB])
                v["A_to_C_over_B_to_C"] = float(S[iC, iA] / S[iC, iB]) if S[iC, iB] > 1e-6 else float("nan")
                v["exact_true_graph"] = bool(called.sum() == 2 and called[iB, iA] and called[iC, iB])
            if "h0" in lat_names:
                ih = lat_names.index("h0")
                v["A_to_h_and_h_to_C_called"] = bool(called[ih, iA] and called[iC, ih])
                v["exact_graph_via_h"] = bool(called.sum() == 2 and called[ih, iA] and called[iC, ih])
            with torch.no_grad():
                Xte = torch.tensor(X[te], dtype=torch.float32)
                if start:
                    kdte = torch.tensor(kd[te]) if (kd is not None and cfg.get("model_kd")) else None
                    fc = m.forecast(Xte[:, 0], Xte[:, 0], T_OBS - 1, kd=kdte); tgt = Xte[:, 1:]
                    if "h0" in lat_names:
                        hz = m.latent_traj(Xte[:, 0], Xte[:, 0], T_OBS - 1, kd=kdte)[..., lat_names.index("h0")].numpy()
                        v["abs_corr_h0_trueB"] = float(abs(np.corrcoef(hz.ravel(), truth[te, 1:, 1].ravel())[0, 1]))
                    if kd is not None:
                        se = ((fc - tgt) ** 2).mean((1, 2)).numpy()
                        v["test_mse_WT_cells"] = float(se[~kd[te]].mean()); v["test_mse_KD_cells"] = float(se[kd[te]].mean())
                        if cfg.get("model_kd"):
                            v["learned_kd_efficiency"] = float(m.kd_eff())
                else:
                    fc = m.forecast(Xte[:, 1], Xte[:, 0], T_OBS - 2); tgt = Xte[:, 2:]
                v["test_full_rollout_mse"] = float(F.mse_loss(fc, tgt))
            res["variants"][name] = v
            if (K, lam) == MARKOV_MODEL:
                main_model = m
            print(cond, seed, name, f"{v['seconds']:.0f}s", v["called_edges"], round(v["A_to_C_strength_rel_max"], 3), flush=True)
    res["baselines"] = baselines(X, obs)
    res["markov"] = markov_test(X, None if start else main_model, te, truth=truth if cond == "full_lownoise" else None)
    OUT.mkdir(parents=True, exist_ok=True)
    json.dump(res, open(OUT / f"{cond}_seed{seed}.json", "w"), indent=2)


