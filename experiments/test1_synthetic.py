"""Test 1 - synthetic sanity check.

Question: when the data really are generated by Boltzmann occupancy, does an occupancy
score recover regulators that a thresholded motif scan misses (weak-site clusters), and can
TF activity (mu) per condition be recovered from expression alone?

Simulation (per seed):
  * G random promoters (1 kb, human-like base composition), T real JASPAR motifs.
  * Per TF: N_STRONG targets with one strong planted site (E <= 1.5 kT) and
            N_WEAK targets with K_WEAK sub-threshold sites (E_thr+0.5 .. E_thr+2.5, i.e. each
            site individually misses a FIMO-style p<1e-4 cutoff).
  * C conditions; mu[t,c] = E_thr[t] - 2 + 1.5*N(0,1)   (TF activity varies across conditions).
  * y[g,c] = sum_t w_t * occ_true[g,t,c] + N(0, SIGMA)   (exact occupancy over all positions).
Truth = planted target pairs. Methods only see sequences + expression (+ a noisy TF-level proxy
for the co-expression baselines).
"""
import json, sys, time
from pathlib import Path
import numpy as np
from scipy.stats import spearmanr
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from bond.pwm import parse_jaspar, logodds, scan_energies
from bond.occupancy import sigmoid
from bond.fit import OccupancyModel, sparse_sites
from bond.metrics import auroc, auprc_ratio

ROOT = Path(__file__).resolve().parents[1]
G, L, T, C = 1500, 1000, 20, 40
N_STRONG, N_WEAK, K_WEAK = 30, 30, 6
SIGMA = 0.3
BG = np.array([0.29, 0.21, 0.21, 0.29])
SEEDS = [0, 1, 2]
PVAL = 1e-4


def pick_motifs(rng):
    ms = [m for m in parse_jaspar(ROOT / "data/raw/jaspar2024_vert_nr.txt")
          if "::" not in m["name"] and 9 <= m["pfm"].shape[1] <= 15]
    idx = rng.choice(len(ms), T, replace=False)
    return [ms[i] for i in idx]


def threshold_E(W, rng, n=400000):
    """E cutoff with P_background(E < thr) = PVAL (single strand), FIMO-like."""
    w = W.shape[0]
    seq = rng.choice(4, size=(n // 100, 100 + w - 1), p=BG).astype(np.int8)
    E, _, _ = scan_energies(seq, W)
    return float(np.quantile(E[:, 0, :].ravel(), PVAL))


def sample_site(W, rng, lo, hi, tries=200000):
    p = np.exp(W) * BG; p /= p.sum(1, keepdims=True)
    smax = W.max(1).sum()
    for _ in range(50):
        # mix PWM sampling with uniform mutation to reach weaker energies
        n = 4000
        s = np.array([rng.choice(4, n, p=p[j]) for j in range(W.shape[0])]).T
        mut = rng.random(s.shape) < rng.uniform(0, 0.35, (n, 1))
        s[mut] = rng.integers(0, 4, mut.sum())
        E = smax - W[np.arange(W.shape[0]), s].sum(1)
        ok = np.nonzero((E >= lo) & (E <= hi))[0]
        if ok.size:
            return s[ok[0]].astype(np.int8)
    raise RuntimeError("could not sample site")


def run(seed):
    rng = np.random.default_rng(seed)
    motifs = pick_motifs(rng)
    Ws = [logodds(m["pfm"], BG) for m in motifs]
    Ethr = np.array([threshold_E(W, rng) for W in Ws])
    seqs = rng.choice(4, size=(G, L), p=BG).astype(np.int8)
    used = np.zeros((G, L), bool)
    truth = np.zeros((G, T), np.int8)  # 0 none, 1 strong, 2 weak
    for t, W in enumerate(Ws):
        w = W.shape[0]
        genes = rng.choice(G, N_STRONG + N_WEAK, replace=False)
        for j, g in enumerate(genes):
            kind = 1 if j < N_STRONG else 2
            nsite = 1 if kind == 1 else K_WEAK
            for _ in range(nsite):
                for _try in range(1000):
                    pos = rng.integers(0, L - w)
                    if not used[g, pos:pos + w].any():
                        break
                lo, hi = (0.0, 1.5) if kind == 1 else (Ethr[t] + 0.5, Ethr[t] + 2.5)
                site = sample_site(W, rng, lo, hi)
                if rng.random() < 0.5:
                    site = (3 - site)[::-1]
                seqs[g, pos:pos + w] = site
                used[g, pos:pos + w] = True
            truth[g, t] = kind
    # true activities and expression
    mu_true = Ethr[:, None] - 2 + 1.5 * rng.standard_normal((T, C))
    w_true = rng.choice([-1, 1], T) * rng.uniform(0.5, 1.5, T)
    Es = [scan_energies(seqs, W)[0] for W in Ws]
    occ_true = np.zeros((G, T, C))
    for t in range(T):
        for c in range(C):
            occ_true[:, t, c] = sigmoid(mu_true[t, c] - Es[t]).sum(axis=(1, 2))
    y = np.einsum("gtc,t->gc", occ_true, w_true) + SIGMA * rng.standard_normal((G, C))

    # ---- scores ----
    S = {}
    S["PWM_max"] = np.stack([-E.min(axis=(1, 2)) for E in Es], 1)
    S["PWM_hits(p<1e-4)"] = np.stack([(E < Ethr[t]).sum(axis=(1, 2)) for t, E in enumerate(Es)], 1).astype(float)
    for off in (-4, -2, 0):
        S[f"OCC_static(mu=Ethr{off:+d})"] = np.stack(
            [sigmoid(Ethr[t] + off - E).sum(axis=(1, 2)) for t, E in enumerate(Es)], 1)
    proxy = mu_true + 1.0 * rng.standard_normal((T, C))  # noisy TF-level readout (like TF mRNA)
    yz = (y - y.mean(1, keepdims=True)) / (y.std(1, keepdims=True) + 1e-9)
    pz = (proxy - proxy.mean(1, keepdims=True)) / proxy.std(1, keepdims=True)
    coex = np.abs(yz @ pz.T) / C
    S["Coexpression(|r|, TF proxy)"] = coex
    S["Motif-pruned coexpression"] = coex - 1.0 * (S["PWM_hits(p<1e-4)"] == 0)
    # BOND fit: learn mu[t,c], w_t from expression only
    eg, et, Ls = [], [], []
    for t, E in enumerate(Es):
        g, _, e = sparse_sites(E, Ethr[t] + 4.0)
        eg.append(g); et.append(np.full(g.size, t)); Ls.append(-e)
    eg, et = np.concatenate(eg), np.concatenate(et)
    Lm = np.repeat(np.concatenate(Ls)[:, None], C, axis=1)
    t0 = time.time()
    model = OccupancyModel(eg, et, Lm, G, T, mu_mode="state", intercept="gene",
                           lam_w=1e-4, lam_mu=1e-3, mu_bound=6.0, mu0=Ethr - 2, mu_center=Ethr - 2)
    model.fit(y, seed=seed, maxiter=3000)
    _, w_hat, mu_hat = model.unpack(model.p)
    occ_hat = model.pair_occupancy(model.p)
    S["BOND_fit(|w|*mean occ)"] = np.abs(w_hat)[None, :] * occ_hat.mean(2)
    S["BOND_fit(|w|*sd occ)"] = np.abs(w_hat)[None, :] * occ_hat.std(2)
    fit_s = time.time() - t0

    lab = truth.ravel() > 0
    out = {"n_pairs": int(lab.size), "n_true": int(lab.sum()), "fit_seconds": fit_s,
           "fit_converged": bool(model.res.success), "n_sparse_sites": int(eg.size), "methods": {}}
    K = int(lab.sum())
    for name, s in S.items():
        s = s.ravel()
        top = np.argsort(-s, kind="stable")[:K]
        strong = truth.ravel() == 1; weak = truth.ravel() == 2; none = truth.ravel() == 0
        out["methods"][name] = dict(
            AUROC_all=auroc(lab, s), AUPRC_ratio_all=auprc_ratio(lab, s),
            AUROC_strong_vs_none=auroc(strong[strong | none], s[strong | none]),
            AUROC_weak_vs_none=auroc(weak[weak | none], s[weak | none]),
            recall_strong_at_topK=float(strong[top].sum() / strong.sum()),
            recall_weak_at_topK=float(weak[top].sum() / weak.sum()))
    rho = np.array([spearmanr(mu_hat[t], mu_true[t])[0] for t in range(T)])
    # (w, mu) are identifiable only up to a joint sign flip when gene intercepts absorb the
    # absolute level; orient each TF so mu_hat correlates positively with the noisy TF proxy.
    flip = np.array([spearmanr(mu_hat[t], proxy[t])[0] < 0 for t in range(T)])
    rho_or = np.where(flip, -rho, rho)
    w_or = np.where(flip, -w_hat, w_hat)
    out["mu_recovery_abs_spearman_median"] = float(np.median(np.abs(rho)))
    out["mu_recovery_spearman_median"] = float(np.median(rho_or))
    out["mu_recovery_spearman_min"] = float(np.min(rho_or))
    out["w_sign_accuracy_raw"] = float(np.mean(np.sign(w_hat) == np.sign(w_true)))
    out["w_sign_accuracy"] = float(np.mean(np.sign(w_or) == np.sign(w_true)))
    out["proxy_vs_mu_spearman_median"] = float(np.median([spearmanr(proxy[t], mu_true[t])[0] for t in range(T)]))
    # weak sites are individually below threshold?
    out["weak_targets_with_zero_hits_frac"] = float(
        (S["PWM_hits(p<1e-4)"].ravel()[truth.ravel() == 2] == 0).mean())
    return out


KEYS = ["mu_recovery_abs_spearman_median", "mu_recovery_spearman_median", "w_sign_accuracy_raw",
        "w_sign_accuracy", "proxy_vs_mu_spearman_median", "weak_targets_with_zero_hits_frac",
        "fit_seconds"]

if __name__ == "__main__":
    (ROOT / "results").mkdir(exist_ok=True)
    if sys.argv[1] == "--seed":
        sd = int(sys.argv[2]); t0 = time.time()
        r = run(sd)
        json.dump(r, open(ROOT / f"results/test1_seed{sd}.json", "w"), indent=2)
        print(f"seed {sd} done in {time.time() - t0:.0f}s converged={r['fit_converged']}")
        sys.exit()
    runs = {str(sd): json.load(open(ROOT / f"results/test1_seed{sd}.json")) for sd in SEEDS}
    res = {"config": dict(G=G, L=L, T=T, C=C, N_STRONG=N_STRONG, N_WEAK=N_WEAK, K_WEAK=K_WEAK,
                          SIGMA=SIGMA, PVAL=PVAL, seeds=SEEDS), "runs": runs}
    names = list(runs["0"]["methods"])
    agg = {n: {k: [float(np.mean([runs[s]["methods"][n][k] for s in runs])),
                   float(np.std([runs[s]["methods"][n][k] for s in runs]))]
               for k in runs["0"]["methods"][n]} for n in names}
    for k in KEYS:
        agg[k] = [float(np.mean([runs[s][k] for s in runs])), float(np.std([runs[s][k] for s in runs]))]
    res["aggregate_mean_sd"] = agg
    json.dump(res, open(ROOT / "results/test1_synthetic.json", "w"), indent=2)
    for n in names:
        a = agg[n]
        print(f"{n:34s} AUROC={a['AUROC_all'][0]:.3f} AUPRCx={a['AUPRC_ratio_all'][0]:.2f} "
              f"strong={a['AUROC_strong_vs_none'][0]:.3f} weak={a['AUROC_weak_vs_none'][0]:.3f} "
              f"recW@K={a['recall_weak_at_topK'][0]:.2f}")
    for k in KEYS:
        print(k, agg[k])
